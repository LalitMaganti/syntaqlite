/// Marker trait for typed dialect handles.
///
/// Every dialect has a concrete `Dialect` struct (generated by codegen) that
/// implements this trait and wraps an [`AnyDialect`]. Use the typed handle
/// when you need access to the dialect's typed AST node types (e.g.
/// `nodes::SelectStmt`). When you only need parsing, formatting, or
/// validation, accept [`AnyDialect`] directly -- it is cheaper to clone
/// and works with any dialect.
pub trait TypedDialect: Into<AnyDialect> + Clone + 'static {}

// ── AnyDialect ───────────────────────────────────────────────────────────────

/// Type-erased dialect handle used by the formatter, analyzer, and LSP.
///
/// `AnyDialect` is the common currency type that all syntaqlite infrastructure
/// accepts. It bundles the dialect (parser tables + version/cflag config) with
/// formatter and semantic-role data.
///
/// # Obtaining an `AnyDialect`
///
/// | Method | When to use |
/// |--------|-------------|
/// | [`sqlite_dialect().erase()`](crate::sqlite_dialect) | Built-in `SQLite`, type-erased. |
/// | [`Dialect::new().into()`](crate::Dialect) | Same, via `Into<AnyDialect>`. |
/// | `AnyDialect::load(path, name)` | Dynamically loaded dialect (feature `dynload`). |
///
/// # Example
///
/// ```
/// use syntaqlite::any::AnyDialect;
/// use syntaqlite::util::SqliteVersion;
///
/// // Obtain the built-in SQLite dialect, then configure it.
/// let dialect: AnyDialect = syntaqlite::sqlite_dialect().erase();
/// let dialect = dialect.with_version(SqliteVersion::V3_39);
/// assert_eq!(dialect.version(), SqliteVersion::V3_39);
/// ```
#[derive(Clone)]
pub struct AnyDialect {
    /// The syntax dialect, which also owns the `SyntaqliteDialectTemplate`
    /// this handle reads formatter/analysis tables from (and, for loaded
    /// dialects, keeps the library alive).
    // Safety invariant: `inner.template_ptr()` points to a valid, immutable,
    // well-formed `CDialectTemplate` whose data tables remain valid and
    // immutable for as long as `inner` is alive. Specifically, whenever a
    // `*_count` field in the template is non-zero, its corresponding pointer is
    // non-null, properly aligned, and valid for reads of that many elements
    // (when `*_count == 0`, the pointer may be null):
    // - `roles_data` points to `roles_count` valid `SemanticRole` values.
    // - `macro_defs_data` points to `macro_defs_count` valid `MacroDef` values.
    // - `fmt_dispatch` points to `fmt_dispatch_count` `u32` entries.
    // - `fmt_ops` points to `fmt_ops_count` bytes.
    // - `fmt_str_offsets` points to `fmt_str_count + 1` monotonically
    //   non-decreasing byte offsets into `fmt_str_data`, and (when the final
    //   offset `fmt_str_offsets[fmt_str_count]` is non-zero) `fmt_str_data` is
    //   non-null and points to valid UTF-8 bytes covering
    //   `0..fmt_str_offsets[fmt_str_count]`.
    // - `fmt_enum_display` points to `fmt_enum_display_count` `u16` entries.
    // - `fmt_prec_table` points to `fmt_prec_table_count` bytes.
    // - `fmt_expr_meta` points to `fmt_expr_meta_count` `u32` entries.
    inner: SyntaxDialect,
    /// Rust-side cflag set (all 42 flags, u64 bitset). Distinct from the
    /// C-ABI `SqliteSyntaxFlags` stored in the dialect — this covers
    /// non-parser flags like `SQLITE_ENABLE_MATH_FUNCTIONS`.
    ext_cflags: crate::util::SqliteFlags,
}

// Dialect handles are shared across threads (LSP, RPC); keep that true now
// that it follows from the fields rather than an `unsafe impl`.
const _: () = {
    const fn assert_send_sync<T: Send + Sync>() {}
    assert_send_sync::<AnyDialect>();
};

impl AnyDialect {
    /// Construct from a reference to the dialect's static template data.
    ///
    /// Derives the syntax dialect handle from the dialect template,
    /// using default version (latest) and empty cflags.
    ///
    /// # Safety
    ///
    /// While the `&'static` reference guarantees the [`ffi::CDialectTemplate`]
    /// struct itself is valid for the program lifetime, `CDialectTemplate` is a
    /// `#[repr(C)]` FFI struct whose fields are raw pointers and counts. The
    /// caller must ensure `data` is well-formed (as produced by
    /// `syntaqlite-buildtools`) and that all of its data tables remain valid and
    /// immutable for `'static`:
    /// - For every non-zero `*_count` field (`roles_count`, `macro_defs_count`,
    ///   `fmt_dispatch_count`, `fmt_ops_count`, `fmt_str_count`,
    ///   `fmt_enum_display_count`, `fmt_prec_table_count`,
    ///   `fmt_expr_meta_count`), the corresponding pointer is non-null,
    ///   properly aligned, and valid for reads of that many elements (or
    ///   `fmt_str_count + 1` offsets for `fmt_str_offsets` and
    ///   `0..fmt_str_offsets[fmt_str_count]` valid UTF-8 bytes for
    ///   `fmt_str_data`).
    /// - All syntax-level tables and function pointers required by
    ///   [`SyntaxDialect::from_dialect_template`] are valid.
    pub(crate) unsafe fn from_data(data: &'static ffi::CDialectTemplate) -> Self {
        // SAFETY: `data` is a `'static` reference, and the caller guarantees its
        // internal raw table and function pointers satisfy `SyntaxDialect` and
        // `AnyDialect`'s safety invariants for `'static`.
        let inner = unsafe { SyntaxDialect::from_dialect_template(std::ptr::from_ref(data)) };
        AnyDialect {
            inner,
            ext_cflags: crate::util::SqliteFlags::default(),
        }
    }

    /// Construct from a [`ffi::CDialect`] value (the C `SyntaqliteDialect`).
    ///
    /// Extracts the template pointer and version/cflags from the C value type,
    /// constructing a dialect handle with the configured version and cflags.
    ///
    /// # Safety
    ///
    /// `dialect.template` must point to a valid, well-formed
    /// [`ffi::CDialectTemplate`] (satisfying the table pointer/count invariants
    /// documented on [`Self::from_c_dialect_ptr`]) whose data tables remain
    /// valid and immutable for at least as long as this `AnyDialect` (and all
    /// its clones).
    #[doc(hidden)]
    pub unsafe fn from_c_dialect(dialect: ffi::CDialect) -> Self {
        // SAFETY: The caller guarantees `dialect.template` points to a valid,
        // well-formed `CDialectTemplate` for the lifetime of the returned
        // `AnyDialect`.
        let mut inner = unsafe { SyntaxDialect::from_dialect_template(dialect.template) };
        inner = inner
            .with_version(SqliteVersion::from_int(dialect.sqlite_version))
            .with_cflags(syntaqlite_syntax::util::SqliteSyntaxFlags::from_raw(
                dialect.cflags,
            ));
        AnyDialect {
            inner,
            ext_cflags: crate::util::SqliteFlags::default(),
        }
    }

    /// Wrap a syntax-level dialect handle, with no extra cflags.
    pub(crate) fn from_syntax_dialect(inner: SyntaxDialect) -> Self {
        AnyDialect {
            inner,
            ext_cflags: crate::util::SqliteFlags::default(),
        }
    }

    /// Return a reference to the dialect template.
    #[inline]
    fn template(&self) -> &ffi::CDialectTemplate {
        // SAFETY: By `AnyDialect`'s safety invariant, `inner.template_ptr()`
        // points to a valid `CDialectTemplate` for as long as `inner` is alive,
        // and the borrow of `self` keeps `inner` alive.
        unsafe { &*self.inner.template_ptr() }
    }

    /// The syntax dialect handle for this dialect.
    pub fn syntax_dialect(&self) -> &SyntaxDialect {
        &self.inner
    }

    /// The semantic role table for this dialect, indexed by node tag.
    pub(crate) fn roles(&self) -> &[SemanticRole] {
        const { assert!(align_of::<SemanticRole>() == 1) };
        let raw = self.template();
        if raw.roles_count == 0 {
            return &[];
        }
        assert!(
            !raw.roles_data.is_null(),
            "roles_data is null with non-zero roles_count ({})",
            raw.roles_count,
        );
        // SAFETY: The early return above ensures `raw.roles_count > 0`, and the
        // assert ensures `raw.roles_data` is non-null. Because `raw.roles_count`
        // is non-zero, `AnyDialect`'s safety invariant guarantees that
        // `raw.roles_data` points to `raw.roles_count` valid `SemanticRole`
        // values (alignment 1) that live at least as long as `self`.
        unsafe {
            std::slice::from_raw_parts(
                raw.roles_data.cast::<SemanticRole>(),
                raw.roles_count as usize,
            )
        }
    }

    /// The macro definition descriptors for this dialect.
    ///
    /// Each entry describes an AST node type that defines a template macro
    /// (e.g. `CREATE PERFETTO MACRO`). Empty for dialects without macros.
    pub(crate) fn macro_defs(&self) -> &[MacroDef] {
        const { assert!(align_of::<MacroDef>() == 1) };
        let raw = self.template();
        if raw.macro_defs_count == 0 {
            return &[];
        }
        assert!(
            !raw.macro_defs_data.is_null(),
            "macro_defs_data is null with non-zero macro_defs_count ({})",
            raw.macro_defs_count,
        );
        // SAFETY: The early return above ensures `raw.macro_defs_count > 0`, and
        // the assert ensures `raw.macro_defs_data` is non-null. Because
        // `raw.macro_defs_count` is non-zero, `AnyDialect`'s safety invariant
        // guarantees that `raw.macro_defs_data` points to
        // `raw.macro_defs_count` valid `MacroDef` values (alignment 1) that live
        // at least as long as `self`.
        unsafe {
            std::slice::from_raw_parts(
                raw.macro_defs_data.cast::<MacroDef>(),
                raw.macro_defs_count as usize,
            )
        }
    }

    /// Whether this dialect has formatter data.
    pub(crate) fn has_fmt_data(&self) -> bool {
        self.template().fmt_str_count > 0
    }

    /// The formatter bytecode for a node tag, one 6-byte op per element (see
    /// [`split_fmt_op`]).
    pub(crate) fn fmt_dispatch(
        &self,
        tag: syntaqlite_syntax::any::AnyNodeTag,
    ) -> Option<&[[u8; 6]]> {
        let raw = self.template();
        let tag_idx = u32::from(tag) as usize;
        if raw.fmt_dispatch.is_null() || tag_idx >= raw.fmt_dispatch_count as usize {
            return None;
        }
        // SAFETY: `fmt_dispatch` is non-null and `tag_idx < fmt_dispatch_count`;
        // by `AnyDialect`'s safety invariant `fmt_dispatch` is valid for
        // `fmt_dispatch_count` entries.
        let packed = unsafe { *raw.fmt_dispatch.add(tag_idx) };
        let offset = (packed >> 16) as u16;
        let length = (packed & 0xFFFF) as u16;
        if offset == 0xFFFF {
            return None;
        }
        let byte_offset = offset as usize * 6;
        let byte_len = length as usize * 6;
        assert!(
            byte_offset + byte_len <= raw.fmt_ops_count as usize,
            "fmt_dispatch range {}..{} out of bounds (fmt_ops_count={})",
            byte_offset,
            byte_offset + byte_len,
            raw.fmt_ops_count,
        );
        if byte_len == 0 || raw.fmt_ops.is_null() {
            assert!(byte_len == 0, "fmt_ops is null with non-zero byte_len");
            return Some(&[]);
        }
        // SAFETY: `fmt_ops` is non-null and `byte_offset + byte_len <= fmt_ops_count`;
        // by `AnyDialect`'s safety invariant `fmt_ops` is valid for
        // `fmt_ops_count` bytes for the lifetime of `self`. `[u8; 6]` has
        // alignment 1, and `byte_len` is `length` ops of 6 bytes.
        Some(unsafe {
            std::slice::from_raw_parts(
                raw.fmt_ops.add(byte_offset).cast::<[u8; 6]>(),
                usize::from(length),
            )
        })
    }

    /// Look up a string from the fmt string table by index (CSR encoding).
    ///
    /// # Panics
    /// Panics if `idx` is out of bounds for this dialect's string table.
    #[inline]
    pub(crate) fn fmt_string(&self, idx: u16) -> &str {
        let raw = self.template();
        let idx = idx as usize;
        assert!(
            !raw.fmt_str_offsets.is_null() && idx < raw.fmt_str_count as usize,
            "fmt_string index {idx} out of bounds (count={})",
            raw.fmt_str_count,
        );
        // SAFETY: `fmt_str_offsets` is non-null and `idx < fmt_str_count`; by
        // `AnyDialect`'s safety invariant `fmt_str_offsets` has `fmt_str_count + 1`
        // entries, so both `idx` and `idx + 1` are in bounds.
        let (start, end) = unsafe {
            (
                *raw.fmt_str_offsets.add(idx) as usize,
                *raw.fmt_str_offsets.add(idx + 1) as usize,
            )
        };
        if start == end {
            return "";
        }
        assert!(
            !raw.fmt_str_data.is_null() && start < end,
            "invalid fmt_string byte range {start}..{end}",
        );
        // SAFETY: `fmt_str_data` is non-null and `start < end`; by `AnyDialect`'s
        // safety invariant `fmt_str_data` covers `0..fmt_str_offsets[fmt_str_count]`
        // with valid UTF-8 bytes for the lifetime of `self`.
        unsafe {
            std::str::from_utf8_unchecked(std::slice::from_raw_parts(
                raw.fmt_str_data.add(start),
                end - start,
            ))
        }
    }

    /// Look up a value in the enum display table.
    ///
    /// # Panics
    /// Panics if `idx` is out of bounds for this dialect's enum display table.
    pub(crate) fn fmt_enum_display_val(&self, idx: usize) -> u16 {
        let raw = self.template();
        assert!(
            !raw.fmt_enum_display.is_null() && idx < raw.fmt_enum_display_count as usize,
            "fmt_enum_display index {idx} out of bounds (count={})",
            raw.fmt_enum_display_count,
        );
        // SAFETY: `fmt_enum_display` is non-null and `idx < fmt_enum_display_count`;
        // by `AnyDialect`'s safety invariant `fmt_enum_display` is valid for
        // `fmt_enum_display_count` entries.
        unsafe { *raw.fmt_enum_display.add(idx) }
    }

    /// Look up `(prec, group)` from the precedence table at `base + ordinal`.
    ///
    /// # Panics
    /// Panics if `base + ordinal` is out of bounds for this dialect's precedence table.
    pub(crate) fn fmt_prec_lookup(&self, base: u16, ordinal: u32) -> (u8, u8) {
        let raw = self.template();
        let count = raw.fmt_prec_table_count as usize;
        let byte_idx = (base as usize)
            .checked_add(ordinal as usize)
            .and_then(|idx| idx.checked_mul(2))
            .filter(|&idx| {
                !raw.fmt_prec_table.is_null() && idx.checked_add(1).is_some_and(|end| end < count)
            })
            .unwrap_or_else(|| {
                panic!(
                    "fmt_prec_lookup byte index out of bounds (base={base}, ordinal={ordinal}, count={count})"
                )
            });
        // SAFETY: `fmt_prec_table` is non-null and `byte_idx + 1 < fmt_prec_table_count`;
        // by `AnyDialect`'s safety invariant `fmt_prec_table` is valid for
        // `fmt_prec_table_count` bytes.
        unsafe {
            let prec = *raw.fmt_prec_table.add(byte_idx);
            let group = *raw.fmt_prec_table.add(byte_idx + 1);
            (prec, group)
        }
    }

    /// Look up the expr-meta for a node tag.
    pub(crate) fn fmt_expr_meta(
        &self,
        tag: syntaqlite_syntax::any::AnyNodeTag,
    ) -> Option<(u8, u16)> {
        let raw = self.template();
        let tag_idx = u32::from(tag) as usize;
        if raw.fmt_expr_meta.is_null() || tag_idx >= raw.fmt_expr_meta_count as usize {
            return None;
        }
        // SAFETY: `fmt_expr_meta` is non-null and `tag_idx < fmt_expr_meta_count`;
        // by `AnyDialect`'s safety invariant `fmt_expr_meta` is valid for
        // `fmt_expr_meta_count` entries.
        let packed = unsafe { *raw.fmt_expr_meta.add(tag_idx) };
        if packed == 0xFFFF_FFFF {
            return None;
        }
        let op_field_idx = (packed & 0xFF) as u8;
        let prec_table_base = ((packed >> 8) & 0xFFFF) as u16;
        Some((op_field_idx, prec_table_base))
    }

    /// Return a copy of this dialect targeting a specific `SQLite` version.
    ///
    /// The version affects which syntax is accepted by the parser and which
    /// built-in functions are available during validation.
    ///
    /// ```
    /// # use syntaqlite::util::SqliteVersion;
    /// let dialect = syntaqlite::sqlite_dialect().erase()
    ///     .with_version(SqliteVersion::V3_35);
    /// assert_eq!(dialect.version(), SqliteVersion::V3_35);
    /// ```
    #[must_use]
    pub fn with_version(mut self, version: SqliteVersion) -> Self {
        self.inner = self.inner.with_version(version);
        self
    }

    /// Return a copy of this dialect with the given compile-time flags.
    ///
    /// Compile-time flags model `SQLITE_ENABLE_*` / `SQLITE_OMIT_*` options.
    /// They control which built-in functions are available during validation.
    ///
    /// ```
    /// use syntaqlite::util::{SqliteFlag, SqliteFlags};
    ///
    /// let dialect = syntaqlite::sqlite_dialect().erase()
    ///     .with_cflags(SqliteFlags::default().with(SqliteFlag::EnableMathFunctions));
    /// assert!(dialect.cflags().has(SqliteFlag::EnableMathFunctions));
    /// ```
    #[must_use]
    pub fn with_cflags(mut self, flags: crate::util::SqliteFlags) -> Self {
        self.ext_cflags = flags;
        self.inner = self.inner.with_cflags(flags.into());
        self
    }

    /// Active compile-time compatibility flags set on this dialect.
    pub fn cflags(&self) -> crate::util::SqliteFlags {
        self.ext_cflags
    }

    /// Target `SQLite` version configured on this dialect.
    pub fn version(&self) -> SqliteVersion {
        self.inner.version()
    }

    /// C-parser compile-time compatibility flags (parser flags, indices 0–21).
    pub fn syntax_cflags(&self) -> syntaqlite_syntax::util::SqliteSyntaxFlags {
        self.inner.cflags()
    }

    /// Construct an [`AnyDialect`] from a reference to a `'static`
    /// [`ffi::CDialectTemplate`] returned by a dialect's
    /// `syntaqlite_<name>_dialect_template()` `extern "C"` function.
    ///
    /// **This is only intended for external dialect implementations and WASM side-module
    /// loaders.** Normal application code should use [`crate::sqlite_dialect()`] or the
    /// `dynload` feature's `AnyDialect::load` instead.
    ///
    /// # Safety
    ///
    /// While the `&'static` reference guarantees the [`ffi::CDialectTemplate`]
    /// struct itself is valid for the program lifetime, `CDialectTemplate` is a
    /// `#[repr(C)]` FFI struct whose fields are raw pointers and counts. The
    /// caller must ensure `ptr` is well-formed (as produced by
    /// `syntaqlite-buildtools`) and that all of its data tables remain valid and
    /// immutable for `'static`:
    /// - For every non-zero `*_count` field (`roles_count`, `macro_defs_count`,
    ///   `fmt_dispatch_count`, `fmt_ops_count`, `fmt_str_count`,
    ///   `fmt_enum_display_count`, `fmt_prec_table_count`,
    ///   `fmt_expr_meta_count`), the corresponding pointer is non-null,
    ///   properly aligned, and valid for reads of that many elements (or
    ///   `fmt_str_count + 1` offsets for `fmt_str_offsets` and
    ///   `0..fmt_str_offsets[fmt_str_count]` valid UTF-8 bytes for
    ///   `fmt_str_data`).
    /// - All syntax-level tables and function pointers required by
    ///   [`SyntaxDialect::from_dialect_template`] are valid.
    pub unsafe fn from_c_dialect_ptr(ptr: &'static ffi::CDialectTemplate) -> Self {
        // SAFETY: Forwarded from caller; see `# Safety` above.
        unsafe { Self::from_data(ptr) }
    }

    /// Load a dialect from a shared library (`.so` / `.dylib` / `.dll`).
    ///
    /// Resolves the `syntaqlite_<name>_dialect_template` symbol (or
    /// `syntaqlite_dialect_template` when `name` is `None`), which returns a pointer to
    /// a `SyntaqliteDialectTemplate` struct bundling dialect + all data arrays.
    ///
    /// # Errors
    /// Returns `Err` if the library cannot be opened, the dialect symbol is
    /// absent, or the symbol returns a null template pointer.
    ///
    /// # Safety
    ///
    /// The caller must ensure that:
    /// - Loading `path` (including running its dynamic library initializers and
    ///   destructors) is sound.
    /// - If the resolved symbol (`syntaqlite_<name>_dialect_template` or
    ///   `syntaqlite_dialect_template`) exists in the library, it is a function
    ///   with ABI `extern "C" fn() -> *const SyntaqliteDialectTemplate` that is
    ///   sound to call with no arguments.
    /// - If the pointer returned by that function is non-null, it points to a
    ///   valid, well-formed `SyntaqliteDialectTemplate` (satisfying the table
    ///   pointer/count invariants documented on [`Self::from_c_dialect_ptr`])
    ///   whose data tables remain valid and immutable for as long as the library
    ///   remains loaded.
    ///
    /// The library stays loaded while any clone of the returned handle, or
    /// any parser/tokenizer/formatter built from one, is alive.
    #[cfg(feature = "dynload")]
    pub unsafe fn load(path: &str, name: Option<&str>) -> Result<Self, String> {
        // SAFETY: The caller guarantees that loading `path` and running its
        // library initializers/destructors is sound.
        let lib = unsafe {
            libloading::Library::new(path).map_err(|e| format!("failed to load {path:?}: {e}"))?
        };

        let sym: String = match name {
            Some(n) => format!("syntaqlite_{n}_dialect_template"),
            None => "syntaqlite_dialect_template".to_string(),
        };

        // Resolve the single dialect symbol and call it to get the data pointer.
        // SAFETY: The caller guarantees that if `sym` is present in `lib`, it has
        // signature `unsafe extern "C" fn() -> *const ffi::CDialectTemplate` and
        // is sound to invoke. `func` is called immediately and dropped before
        // `lib` is moved into `owner`.
        let data: *const ffi::CDialectTemplate = unsafe {
            let func: libloading::Symbol<
                '_,
                unsafe extern "C" fn() -> *const ffi::CDialectTemplate,
            > = lib
                .get(sym.as_bytes())
                .map_err(|e| format!("symbol {sym:?} not found in {path:?}: {e}"))?;
            func()
        };
        if data.is_null() {
            return Err(format!("{sym:?} returned a null dialect template pointer"));
        }

        let owner: std::sync::Arc<dyn Send + Sync> = std::sync::Arc::new(lib);
        // SAFETY: `data` is non-null, and the caller guarantees it points to a
        // valid, well-formed `CDialectTemplate` in `lib` that stays valid while
        // `lib` is loaded; `owner` keeps `lib` loaded for as long as the
        // returned dialect (or any clone / parser / tokenizer built from it) is
        // alive.
        let inner = unsafe { SyntaxDialect::from_dialect_template_with_owner(data, owner) };
        Ok(AnyDialect {
            inner,
            ext_cflags: crate::util::SqliteFlags::default(),
        })
    }
}

impl std::ops::Deref for AnyDialect {
    type Target = SyntaxDialect;
    fn deref(&self) -> &SyntaxDialect {
        &self.inner
    }
}

impl std::ops::DerefMut for AnyDialect {
    fn deref_mut(&mut self) -> &mut SyntaxDialect {
        &mut self.inner
    }
}

/// Split one formatter op into its opcode, `a` operand, and little-endian
/// `b` and `c` operands.
pub(crate) fn split_fmt_op(op: [u8; 6]) -> (u8, u8, u16, u16) {
    let [opcode, a, b0, b1, c0, c1] = op;
    (
        opcode,
        a,
        u16::from_le_bytes([b0, b1]),
        u16::from_le_bytes([c0, c1]),
    )
}

